/**
 * Проигрыш главной темы: соло баса, марш, подъём, кульминация и развязка — шестнадцать
 * тактов посреди музыки меню.
 *
 * **Соло баса открывает проигрыш** (решение хозяина проекта): бас-гитара одна проводит
 * лейтмотив в своём регистре, а всё прочее отступает. Тема, сыгранная внизу и почти без
 * сопровождения, слышна иначе, чем медью наверху, — слух узнаёт её заново и запоминает, а
 * кульминация потом возвращает её во весь голос.
 *
 * **Взяты жанровые приёмы стадионного рока, а не чья-то пьеса:** военные барабаны (томы
 * вместо бочки), хор «о-о» толпой, марш, который сгущается дробью к кульминации, и тихая
 * развязка после неё. Это общий язык жанра — так строят проигрыши десятки групп. Нот и распева
 * чужих песен здесь нет: в кульминации хор поёт НАШ лейтмотив (`leitmotif.ts`), а гармония
 * марша и подъёма своя.
 *
 * Аккорды — ступенями лада темы. Марш ходит вокруг VI и iv, не касаясь тоники: слух ждёт
 * дома, и подъём на iv–VII это ожидание натягивает. Кульминация разрешает его гармонией самой
 * темы, а развязка садится на тонику и держит её — точка в конце долгого предложения.
 */

export type BridgePart = 'bassSolo' | 'march' | 'rise' | 'climax' | 'resolve';

export interface BridgeBar {
  part: BridgePart;
  /** Аккорд такта — ступень лада темы. */
  chord: number;
  /** Номер такта внутри своей части. */
  barInPart: number;
}

/** План проигрыша: части по порядку; `null` — аккорды берутся у самой темы. */
const PLAN: { part: BridgePart; chords: readonly number[] | null }[] = [
  { part: 'bassSolo', chords: null },
  { part: 'march', chords: [5, 3, 5, 6] },
  { part: 'rise', chords: [3, 6] },
  { part: 'climax', chords: null },
  { part: 'resolve', chords: [0, 0] },
];

/** Такты проигрыша под данную гармонию темы. */
export function bridgeBars(themeChords: readonly number[]): BridgeBar[] {
  return PLAN.flatMap(({ part, chords }) =>
    (chords ?? themeChords).map((chord, barInPart) => ({ part, chord, barInPart })));
}
