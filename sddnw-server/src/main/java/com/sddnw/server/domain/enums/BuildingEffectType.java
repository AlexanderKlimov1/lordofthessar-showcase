package com.sddnw.server.domain.enums;

/**
 * Что здание или особенность расы даёт колонии — п. 10 и п. 7.
 * <p>
 * Действие это тип и количество: «еды с фермера — 1», «вместимости — 2». Действия одной
 * колонии складываются, поэтому и новое здание, и новая особенность расы описываются
 * набором таких пар в своём файле и не требуют правок кода. Раса работает на колонии
 * как вечная постройка, поэтому набор типов у них общий.
 */
public enum BuildingEffectType {

    /** Еда за ход независимо от числа фермеров. */
    FOOD_FLAT,

    /** Прибавка к еде с каждого фермера. */
    FOOD_PER_FARMER,

    /** Производство за ход независимо от числа рабочих. */
    PRODUCTION_FLAT,

    /** Прибавка к производству с каждого рабочего. */
    PRODUCTION_PER_WORKER,

    /**
     * Производство с каждого жителя колонии, чем бы он ни был занят, — п. 10.
     * <p>
     * Так работает рециклотрон MOO II: он перерабатывает мусор, а мусорят все, не одни
     * рабочие. Эта прибавка ещё и не пачкает планету — грязь считается без неё, как и без
     * твёрдого производства зданий.
     */
    PRODUCTION_PER_COLONIST,

    /** Очки исследований за ход независимо от числа учёных. */
    RESEARCH_FLAT,

    /** Прибавка к очкам исследований с каждого учёного. */
    RESEARCH_PER_SCIENTIST,

    /** Прибавка к вместимости планеты в жителях. */
    MAX_POPULATION,

    /** Прибавка к приросту населения за ход в тысячах жителей. */
    POPULATION_GROWTH_K,

    /** Прибавка к налоговому доходу колонии в процентах. */
    INCOME_PERCENT,

    /**
     * Кредиты за ход сверх налога с жителей — п. 4.1.
     * <p>
     * «Special income» оригинала: золотые жилы дают колонии ровно пять кредитов, самоцветы
     * — десять, и от числа жителей это не зависит вовсе. Процентом такое не выражается:
     * на колонии в одного жителя процент от налога — это ноль.
     */
    INCOME_FLAT,

    /**
     * Прибавка к приросту населения в процентах — п. 7. Ею отличаются расы: плодовитые
     * растут вдвое быстрее, медленно растущие — вдвое медленнее.
     */
    GROWTH_PERCENT,

    /**
     * Процент к выработке фермера — п. 7. В MOO II так работают правительства и слабые
     * фермеры: объединение поднимает еду с фермера в полтора раза, плохие фермеры роняют
     * её на четверть (две единицы обращаются в полторы — целым числом это не записать).
     * Процент считается от выработки фермера, а не от еды колонии: еда со зданий вроде
     * гидропонной фермы идёт мимо него, как и в оригинале.
     */
    FOOD_PERCENT,

    /** Процент к выработке рабочего — п. 7: так поднимает производство объединение. */
    PRODUCTION_PERCENT,

    /**
     * Процент к выработке учёного — п. 7: демократия прибавляет половину, феодализм
     * отнимает её же. Лаборатории считаются отдельно и под процент не попадают —
     * в MOO II штраф феодализма тоже не трогает автоматическую науку зданий.
     */
    RESEARCH_PERCENT,

    /**
     * Сколько раз грязное производство делится пополам, прежде чем с него считают
     * уборку, — п. 10.
     * <p>
     * Так устроены очистные сооружения MOO II: с переработчиком отходов делитель грязи
     * равен двум, с атмосферным преобразователем — четырём, а с обоими — восьми
     * (StrategyWiki, Calculations). Поэтому здесь считаются <b>деления</b>, а не
     * проценты: они складываются, как складываются все прочие действия зданий (1 + 2 = 3,
     * то есть делитель 8), и оригинальные числа выходят сами собой. Процентами пришлось
     * бы перемножать, а этого набор действий колонии не умеет.
     */
    POLLUTION_HALVINGS,

    /**
     * Процент к терпимости планеты к грязи — п. 10: наноразборщики удваивают её (+100).
     * Считается от терпимости размера планеты.
     */
    POLLUTION_TOLERANCE_PERCENT,

    /**
     * Грязи нет вовсе — п. 10: свалка в ядре планеты убирает загрязнение целиком, и то же
     * умеет неприхотливая раса (п. 7). Количество здесь не значит ничего: хватает
     * наличия.
     */
    POLLUTION_NONE,

    /**
     * Процент к силе защитников колонии в наземном бою — п. 12: казармы и бронеказармы.
     * <p>
     * Только к ОБОРОНЕ: в MOO II нападающий приводит с собой морскую пехоту транспортами,
     * а казармы остаются дома — «the attacker is limited to Marines brought in using troop
     * transports, while the defender can employ both marines from marine barracks and armor
     * units from armor barracks». Считается от базовой силы бойца, как и расовая
     * подготовка, и складывается с ней одной строкой.
     */
    GROUND_DEFENCE_PERCENT,

    /**
     * Прибавка к морали колонии в процентах — п. 10.1: голосимулятор (+20) и Купол Элизия
     * (+30). Сама мораль — не отдельная выработка, а процент ко всему, что дают жители
     * (еда, производство, наука, налог); как она складывается, решает {@link
     * com.sddnw.server.service.MoraleRules}.
     */
    MORALE_PERCENT,

    /**
     * Колония держит гарнизон — п. 10.1: казармы морской пехоты и бронеказармы. Количество
     * не значит ничего, хватает наличия. Нужно морали: у диктатуры и феодализма колония без
     * казарм теряет её пятую часть, у Империума колония С казармами пятую часть получает.
     */
    BARRACKS,

    /**
     * Центр управления чужими — п. 10.1, п. 12: колония, где живут две расы, не теряет
     * морали, а подданные становятся своими за два хода на жителя. Количество не значит
     * ничего, хватает наличия.
     */
    ALIEN_MANAGEMENT,

    /**
     * Столица империи — п. 10.1, п. 6: здание «Capitol» оригинала. Количество не значит
     * ничего, хватает наличия. Пока у империи нет столицы, мораль ВСЕХ её колоний падает
     * ({@code CAPITOL_LOSS_MORALE} строя), а новые лидеры не приходят. Правила — в
     * {@link com.sddnw.server.service.CapitolRules}.
     */
    CAPITOL,

    /**
     * Роботизированный завод — п. 10 (13.10.2026, перенос MOO II): производство без рабочих,
     * зависящее от недр планеты — 5 на сверхбедной, 8 на бедной, 10 на обычной, 15 на
     * богатой, 20 на сверхбогатой («5 PP for Ultra Poor; 8 PP for Poor; 10 PP for Abundant;
     * 15 PP for Rich; 20 PP for Ultra Rich»). Количество — число таких заводов. И, в отличие
     * от прочих твёрдых прибавок, это производство ПАЧКАЕТ планету: «unlike all other flat
     * bonuses from buildings, this one increases pollution». Таблица — в
     * {@code PopulationCalculator.roboticFactory}.
     */
    ROBOTIC_FACTORY,

    /**
     * Еда фермера там, где климат еды не даёт вовсе, — п. 9: биоморфные грибы MOO II поднимают
     * её на токсичных, облучённых и бесплодных планетах «from 0 to 1 per farmer». На прочих
     * климатах не действует — так и в самой игре, вопреки руководству.
     */
    FOOD_ON_LIFELESS,

    /**
     * Подготовка шпионов и контрразведки от технологий — п. 13: нейросканер и сеть
     * кибербезопасности (+10 в MOO II), псионика (+10), телепатическая подготовка (+5).
     * Количество — в единицах оригинала; в очки нашей разведки переводит
     * {@code EspionageService.techPoints}. Колония этот эффект не
     * читает: он действует на всю разведку империи.
     */
    ESPIONAGE_TRAINING,

    /**
     * Прибавка к полезному месту ВСЕХ кораблей империи в процентах — п. 8: мегафлюксеры MOO II
     * («increases available space on all ships by +25%»). Колония этот эффект не читает: его
     * берёт сборка проектов ({@code ShipDesignService.enlarged}).
     */
    SHIP_SPACE_PERCENT,

    /**
     * Гравитационный генератор — п. 4.1 (13.10.2026, перенос MOO II): «eliminates gravity penalties
     * on planets whose gravity is outside the colonist's comfort zone». Количество не значит ничего.
     */
    GRAVITY_NORMAL,

    /**
     * Планетарный радиационный щит — п. 4.1.2 (перенос MOO II): «Radiated climates become Barren».
     * Достроенное здание с этим действием переделывает облучённый климат в бесплодный; тем же
     * действием переделывают его и планетарный щит с барьером — «converts Radiated climates to
     * Barren climates».
     */
    RADIATION_SHIELD,

    /**
     * Пищевые репликаторы — п. 4.1.1 (перенос MOO II 1.50: «1 food costs 1 PP»): чего колонии
     * не хватает на прокорм после подвоза, она делает из своего производства, единица за единицу.
     */
    FOOD_REPLICATOR,

    /**
     * Варп-перехватчик — п. 8 (перенос MOO II): «a radius of 3 full parsecs and slows all enemy
     * movement to 1 parsec per turn». Количество — радиус в парсеках; чужой флот, летящий в эту
     * систему, последние парсеки пути идёт по одному за ход.
     */
    WARP_INTERDICTOR,

    /**
     * Космическая академия — п. 8 (перенос MOO II, {@code CrewRules}): корабли колонии начинают
     * обученными, стоящие в системе получают опыт каждый ход.
     */
    SPACE_ACADEMY
}
