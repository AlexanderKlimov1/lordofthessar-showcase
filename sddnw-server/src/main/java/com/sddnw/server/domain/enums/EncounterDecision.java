package com.sddnw.server.domain.enums;

/**
 * Что игрок решил при встрече флотов — п. 8: напасть или разойтись.
 */
public enum EncounterDecision {

    /** Атаковать чужой флот. Бой считается сразу, если игрок оставил включённым «авто». */
    ATTACK,

    /** Разойтись миром: право нападения переходит второй стороне. */
    IGNORE,

    /**
     * Бомбить колонию — пункт 25, диалог оригинала «Select Combat at …: BOMBARD». Только у
     * беззащитной колонии и только флотом с бомбами ({@code BombardmentRules}).
     */
    BOMBARD
}
