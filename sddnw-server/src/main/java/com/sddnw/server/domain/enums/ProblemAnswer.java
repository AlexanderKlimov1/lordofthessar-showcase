package com.sddnw.server.domain.enums;

/**
 * Ответ хозяина на сообщение о проблеме — field-backlog, пункт 158: круг замыкается.
 * <p>
 * Ответов два, и второй — тоже ответ: «не будем исправлять» со словами и причиной лучше
 * молчания, после которого тестер решает, что писать бесполезно.
 */
public enum ProblemAnswer {

    /** Исправлено — с версией, в которой исправление вышло. */
    FIXED,

    /** Исправлять не будем — с причиной словами. */
    WONT_FIX
}
