package com.sddnw.server.domain.enums;

/**
 * Задача боевого проекта, который собирает сама игра, — п. 8, п. 15 (03.10.2026, просьба
 * хозяина проекта: «ИИ делает дизайн кораблей под разные игровые задачи»).
 * <p>
 * Прежде у ИИ был один проект на корпус — лучший залп, — и флот его был одинаковым против
 * любого врага: ракетчику он подставлял корабли без защиты от ракет, а колонию со звёздной
 * крепостью ломал теми же пушками, что и флот. Задача хранится признаком проекта, а не
 * словом в имени (имя хранится в базе и переименовывается).
 * <p>
 * У проектов, собранных игроком, задачи нет ({@code null}): игра их не толкует.
 */
public enum ShipMission {

    /** Линейный корабль: лучший залп, который помещается в корпус. */
    LINE,

    /**
     * Эскорт: лучи и снаряды с ближней обороной и противоракеты — бережёт строй от ракет
     * (пункт 30). Нужен против того, кто воюет ракетами.
     */
    ESCORT,

    /**
     * Штурмовик: самый тяжёлый одиночный выстрел и бронебойность — ломает платформы обороны
     * колонии (звёздные базы, крепости, батареи), у которых брони и щитов больше, чем у
     * кораблей. Нужен, когда цель войны — защищённая колония: пока цела оборона, десант не
     * садится.
     */
    ASSAULT,

    /**
     * Бомбардировщик (пункт 25): бомбы на всё место. Нужен, когда цель войны десанту не по
     * силам: колонию, которую не взять, бомбят — «выжженная земля» оригинала.
     */
    BOMBER
}
