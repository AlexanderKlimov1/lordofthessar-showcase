package com.sddnw.server.domain.enums;

/**
 * Чем кончилась партия — п. 3.
 * <p>
 * В MOO II путей к победе три: остаться в галактике одному, быть избранным Высшим
 * советом и разбить антаран у самого Антареса. Антаран в игре нет, и на третьем месте
 * здесь удержание особой звезды; появится Антарес — сюда встанет ещё одно значение, а
 * всё остальное в подсчёте победы не изменится.
 */
public enum VictoryKind {

    /** Покорение: у остальных империй не осталось ни одной колонии. */
    CONQUEST("Покорение галактики"),

    /**
     * Высший совет: империю избрали правителем галактики.
     * <p>
     * В оригинале совет собирается время от времени, голосов у империи столько, сколько
     * у неё населения, и для победы нужно две трети голосов галактики.
     */
    COUNCIL("Избрание Высшим советом"),

    /**
     * Удержание Wardenhold: империя одна держала колонию у особой звезды двадцать ходов
     * подряд ({@code WardenholdRules}). Встало на место антаранской победы оригинала —
     * цель у особой звезды, видимая с первого хода.
     */
    WARDENHOLD("Удержание Тессара"),

    /**
     * Итог по могуществу: к трёхсотому ходу партия не кончилась ничем, и победа отдана
     * сильнейшей империи по первой линии графика «Инфо» ({@code MightVictoryRules}).
     */
    MIGHT("Итог по могуществу"),

    /**
     * Признанное поражение — field-backlog, пункт 81: единственный человек партии против ИИ
     * признал поражение, и партия кончилась; победа отдана сильнейшей из оставшихся империй
     * той же мерой, что итог по могуществу. В партии с другими людьми признание партию не
     * кончает — она идёт дальше без сдавшегося, а его империю ведёт ИИ.
     */
    CONCEDED("Признание поражения"),

    /**
     * Досрочная победа — field-backlog, пункт 154: единственный человек партии объявил победу,
     * когда все прочие живые империи вместе слабее его втрое ({@code ConcessionService.DECLARE_RATIO}).
     * Хвост в сто ходов, где исход известен, перестаёт быть обязательным.
     */
    DECLARED("Досрочная победа");

    private final String label;

    VictoryKind(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }
}
