package com.sddnw.server.domain.enums;

/**
 * Каким бывает выстрел — п. 8.
 * <p>
 * На числа боя вид оружия не влияет: урон, попадание и щит считаются одинаково. Он нужен
 * сцене: по одному и тому же событию «залп» луч, снаряд и ракета рисуются по-разному, и
 * становится видно, кто в кого стреляет и чем.
 * <p>
 * Вид приходит из справочника ({@code weapon_kind} в {@code ship-components.json}), а не
 * угадывается по названию: новая пушка получает свой вид там же, где и урон.
 */
public enum WeaponKind {

    /** Луч: бьёт мгновенно, от ствола до цели. */
    BEAM("луч"),

    /** Снаряд: кинетический выстрел, летит к цели. */
    PROJECTILE("снаряд"),

    /** Ракета или торпеда: идёт к цели своим ходом. */
    MISSILE("ракета"),

    /**
     * Бомба — п. 8, backlog, пункт 25: бьёт ТОЛЬКО по планетам — «Ship Weapon that can only be
     * used against planets and only at zero range». В бой корабль на корабль не идёт, в силу
     * флота не входит; её работа — бомбардировка колонии ({@code BombardmentRules}).
     */
    BOMB("бомба");

    private final String label;

    WeaponKind(String label) {
        this.label = label;
    }

    /** Как вид оружия называется в журнале боя. */
    public String getLabel() {
        return label;
    }
}
