package com.sddnw.server.domain.save;

import com.sddnw.server.domain.enums.GalaxySize;

import java.util.List;

/**
 * Слепок партии на конец завершённого хода — то, что лежит в поле {@code state}
 * таблицы {@code game_save}.
 * <p>
 * Слепок не хранит идентификаторов: игроки, звёзды и планеты ссылаются друг на друга
 * номером слота и порядковым номером в списке. Поэтому загрузка создаёт новую партию
 * со своими идентификаторами и не зависит от того, жива ли ещё исходная игра.
 *
 * @param completedTurn номер завершённого хода: состояние снято на его конец
 * @param hostSlot      слот игрока-создателя партии
 */
public record GameSnapshot(
        String name,
        GalaxySize galaxySize,
        Integer widthParsecs,
        Integer heightParsecs,
        Integer starCount,
        Integer completedTurn,
        Integer totalPlayers,
        Integer maxHumanPlayers,
        Long seed,
        Integer hostSlot,
        List<PlayerSnapshot> players,
        List<StarSystemSnapshot> systems,
        /**
         * Идут ли в партии случайные галактические события — п. 11.1; {@code null} в
         * слепках, снятых до них, и тогда партия загружается с событиями, как в оригинале.
         */
        Boolean galacticEvents,
        /**
         * Собирается ли в партии Высший совет — п. 3; {@code null} в слепках, снятых до
         * его возвращения, и тогда читается «собирается», как в оригинале.
         */
        Boolean council,
        /**
         * Избрания совета уже не признали — п. 3; {@code null} в слепках, снятых до
         * отказа, и тогда читается «не отказывались». Отказ в партии ОДИН, и без этого
         * поля его можно было бы повторять сохранением и загрузкой.
         */
        Boolean councilRefused,
        /** Отношения империй — п. 15; {@code null} в слепках, снятых до дипломатии. */
        List<DiplomacyRelationSnapshot> relations,
        /** Флоты по системам — п. 8; {@code null} в слепках, снятых до флотов. */
        List<FleetSnapshot> fleets,
        /**
         * Проекты кораблей империй — п. 8; {@code null} в слепках, снятых до дизайна
         * кораблей. Сохраняются и вытесненные: по ним летают построенные корабли.
         */
        List<ShipDesignSnapshot> shipDesigns,
        /**
         * Рейсы с жителями — п. 4.1.1; {@code null} в слепках, снятых до перевозок.
         * Сохраняются потому, что в них летят живые жители: колония-отправитель их уже
         * лишилась, и потерять рейс значило бы потерять население.
         */
        List<PopulationTransferSnapshot> transfers,
        /**
         * Действуют ли империи ИИ — трек техдолга, пункт 17; {@code null} в слепках, снятых
         * до признака, и тогда читается «действуют». Без поля сохранение партии прогона
         * загружалось бы с ожившими соседями.
         */
        Boolean aiActive,
        /**
         * Побеждает ли удержание Wardenhold — п. 3; {@code null} в слепках, снятых до этого
         * условия, и тогда читается «нет»: старая партия не обязана кончаться по правилу,
         * которого не было, когда её начинали.
         */
        Boolean wardenholdVictory,
        /** Место держателя особой звезды; {@code null} — звезду никто не держит. */
        Integer wardenholdHolderSlot,
        /** С какого хода держатель держит звезду без перерыва. */
        Integer wardenholdSinceTurn,
        /**
         * Подводится ли итог по могуществу — п. 3; {@code null} в слепках, снятых до этого
         * условия, и тогда читается «нет».
         */
        Boolean mightVictory,
        /**
         * Срок хода в секундах — backlog-promo, пункт 11; {@code null} — без срока, в том
         * числе в слепках, снятых до появления срока.
         */
        Integer turnSeconds,
        /**
         * Партия под наблюдением администратора — field-backlog, пункт 197; {@code null} в
         * слепках, снятых до пометки, и тогда читается «нет». Поднятое сохранение пометку
         * несёт: карты, однажды увиденные, загрузкой не становятся тайной.
         */
        Boolean adminWatched,
        /**
         * Лидеры империй — п. 6, трек техдолга, пункт 28; {@code null} в слепках, снятых до этого
         * поля, — тогда лидеров у поднятой партии нет, как и было.
         */
        java.util.List<LeaderSnapshot> leaders,
        /**
         * Партия поднята из файла, выгруженного игроком, — field-backlog, пункт 160; {@code null}
         * в слепках, снятых до этого поля, и тогда читается «нет». Признак переживает сохранения:
         * файл можно было поправить руками, и такая партия не годится для истории и сравнений.
         */
        Boolean imported,
        /** Учебная партия — field-backlog, пункт 41; {@code null} в старых слепках — «нет». */
        Boolean tutorial,
        /** Партию можно смотреть со стороны — пункт 59; {@code null} в старых слепках — «нет». */
        Boolean spectators,
        /** Особенность галактики — пункт 94; {@code null} — нет или старый слепок. */
        String galaxyFeature,
        /** Неделя галактики недели — пункт 146; {@code null} — обычная партия. */
        Integer weeklyWeek,
        /** Партию продолжили после победы — пункт 131; без признака поднятая партия искала бы победы снова. */
        Boolean playedOn,
        /** Уровень сложности партии (пункт 9); {@code null} — обычный или старый слепок. */
        String aiSkill,
        /** Ход итога по могуществу (пункт 24); {@code null} — 300 или старый слепок. */
        Integer mightTurn,
        /** Тихая галактика (пункт 186); {@code null} в старых слепках — «нет». */
        Boolean peacefulAi,
        /** Набор справочников основателя (пункт 42); {@code null} — справочники игры или старый слепок. */
        GameModSnapshot mod
) {
}
