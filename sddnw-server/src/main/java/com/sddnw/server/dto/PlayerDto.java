package com.sddnw.server.dto;

import java.util.UUID;

/** Игрок в лобби и в игре — п. 3.2. */
public record PlayerDto(
        UUID id,
        Integer slot,
        String name,
        String playerType,
        String raceCode,
        String raceName,
        String color,
        UUID homeSystemId,
        Integer credits,

        /** Правительство империи — п. 14; пусто, если раса собрана без него. */
        String government,

        /** Накоплено очков шпионажа — п. 13. */
        Integer espionagePoints,

        /** Грузовых кораблей у империи — п. 4.1.1: они возят еду голодающим колониям. */
        Integer freighters,

        /**
         * Сколько грузовиков занято перевозкой жителей — п. 4.1.1: по одному на единицу
         * населения, пока рейс не дойдёт. Эти еду не возят.
         */
        Integer freightersReserved,

        /**
         * Игрок объявил конец текущего хода — п. 11.1: по этому признаку в интерфейсе
         * видно, кого ещё ждёт партия. У ИИ всегда истина: он никого не задерживает.
         */
        Boolean turnEnded,

        /**
         * Человек ушёл из-за стола, и его империю ведёт ИИ — backlog-promo, пункт 11. Видно
         * всем: соседи должны знать, почему партия его больше не ждёт.
         */
        Boolean away,
        /**
         * Когда игрок последний раз закончил ход или вошёл в партию — field-backlog, пункт 108:
         * по нему клиент решает, показать ли вернувшемуся сводку «пока вас не было».
         */
        java.time.OffsetDateTime lastActionAt,
        /**
         * Через сколько секунд часы передадут империю ИИ — field-backlog, пункт 127. Пусто —
         * не грозит: ход закончен, никто не ждёт, игрок уже ушёл или это не человек.
         */
        Integer aiTakeoverSeconds,
        /**
         * До какого мига игрок в отпуске — field-backlog, пункт 177; пусто — не в отпуске. Видно
         * всем: соседи должны знать, почему его не ждут и сколько ещё.
         */
        java.time.OffsetDateTime vacationUntil,
        /** Глава партии — field-backlog, пункт 54 ({@code ChapterRules}): 1…5. */
        Integer chapter,
        /** Кому этот игрок показал свою империю как ученик — пункт 184; пусто — никому. */
        UUID mentorPlayerId,
        /** Приходило ли империи хоть одно предложение службы лидера — пункт 27. */
        Boolean leadersSeen,
        /** Знак «с нами с раннего доступа» — пункт 147: за время, а не за сумму; в игре не даёт ничего. */
        Boolean earlyBird,
        /** Знак спутника — подарок за доигранную по приглашению партию (пункты 50, 174), 0…3. */
        Integer companions,
        /** Неистраченные очки эволюционной мутации (п. 7): пока они есть, своему игроку открывается окно выбора. */
        Integer mutationPicks
) {
}
