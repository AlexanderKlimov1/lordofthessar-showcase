package com.sddnw.server.service;

/**
 * Прогноз встречи флотов — field-backlog, пункты 84 и 153.
 * <p>
 * Пять фрегатов против двух линкоров выглядят перевесом по числу кораблей, а решает бой не
 * число, а сила. Поэтому окно встречи называет силу сторон и исход словами — той же мерой, что
 * решает быстрый бой ({@code stub/SpaceBattleService}: сильнейший побеждает).
 * <p>
 * <b>Честно и с разбросом.</b> Быстрый бой решает сила напрямую, но тактический — нет: там
 * дальность, меткость и выбитые системы, и перевес в несколько процентов ничего не обещает.
 * Поэтому «вероятная победа» — только при перевесе не меньше {@link #MARGIN_PERCENT}, а ближе
 * — «исход неясен». Число — реконструкция: оно отделяет «очевидно» от «как повезёт» и правится
 * только здесь.
 * <p>
 * <b>Только по видимому.</b> Сила соперника считается по его кораблям, а их состав виден лишь
 * увиденными технологиями (п. 15, {@code TechSightService}): пока хоть одна технология на его
 * кораблях и платформах не увидена, прогноз называет силу неизвестной, а не угадывает её.
 */
public final class EncounterForecastRules {

    /** Перевес, начиная с которого исход назван вероятным, — в процентах силы слабейшего. */
    public static final int MARGIN_PERCENT = 25;

    /** Исход словами. */
    public enum Forecast {
        /** Вероятная победа: своя сила больше на перевес и выше. */
        LIKELY_WIN,
        /** Исход неясен: силы близки. */
        UNCLEAR,
        /** Вероятное поражение. */
        LIKELY_LOSS,
        /** Сила соперника не видна: технологии на его кораблях не увидены. */
        UNKNOWN
    }

    private EncounterForecastRules() {
    }

    /** Исход по силам сторон; сила соперника пуста — не видна. */
    public static Forecast forecast(Integer yours, Integer theirs) {
        if (theirs == null) {
            return Forecast.UNKNOWN;
        }
        if (yours * 100L >= theirs * (100L + MARGIN_PERCENT) && yours > theirs) {
            return Forecast.LIKELY_WIN;
        }
        if (theirs * 100L >= yours * (100L + MARGIN_PERCENT) && theirs > yours) {
            return Forecast.LIKELY_LOSS;
        }
        return Forecast.UNCLEAR;
    }
}
